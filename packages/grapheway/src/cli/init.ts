/**
 * `grapheway init` — the 60-second adoption path.
 *
 * Detects the project, writes a real config (optionally generated from a
 * live probe of an existing site), and mounts the agent surface:
 *
 *   - Next.js App Router → middleware + one route handler
 *   - Express / Hono / node:http → config + exact mount snippet
 *   - static hosts → config + generated llms.txt / agents.txt / robots /
 *     sitemap files, with a pointer to `grapheway gateway` for MCP
 *
 * No telemetry, no network calls unless you pass `--url`.
 */

import { constants } from "node:fs";
import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import type { GraphewayConfig } from "../core/index.js";
import { generateAll } from "../compat/index.js";
import { probeSite } from "../probe/index.js";

export type Framework = "next" | "express" | "hono" | "node" | "static";

export interface InitOptions {
  /** Project root. Defaults to `process.cwd()`. */
  dir?: string;
  /** Existing site to probe into a real config. */
  url?: string;
  /** Override the detected site name. */
  name?: string;
  /** Override framework detection. */
  framework?: Framework;
  /** Overwrite existing files. */
  force?: boolean;
  /** Page budget when `--url` is used (default 20). */
  maxPages?: number;
}

export interface InitResult {
  framework: Framework;
  /** Files created, relative to the project root. */
  files: string[];
  /** Files left untouched because they already existed. */
  skipped: string[];
  /** True when the config came from a live probe. */
  probed: boolean;
  /** Human-readable next steps. */
  nextSteps: string[];
}

async function exists(path: string): Promise<boolean> {
  try {
    await access(path, constants.F_OK);
    return true;
  } catch {
    return false;
  }
}

/** Detect the framework from project files, without executing anything. */
export async function detectFramework(dir: string): Promise<Framework> {
  for (const name of ["next.config.ts", "next.config.js", "next.config.mjs", "next.config.mts"]) {
    if (await exists(join(dir, name))) return "next";
  }
  if ((await exists(join(dir, "app"))) || (await exists(join(dir, "src", "app")))) return "next";

  const pkgPath = join(dir, "package.json");
  if (await exists(pkgPath)) {
    try {
      const pkg = JSON.parse(await readFile(pkgPath, "utf-8")) as {
        dependencies?: Record<string, string>;
        devDependencies?: Record<string, string>;
      };
      const deps = { ...(pkg.dependencies ?? {}), ...(pkg.devDependencies ?? {}) };
      if (deps.next) return "next";
      if (deps.hono) return "hono";
      if (deps.express) return "express";
      if (deps.astro || deps["@astrojs/node"]) return "static";
    } catch {
      // Invalid package.json: fall through to filesystem heuristics.
    }
  }

  for (const name of ["astro.config.mjs", "astro.config.ts", "astro.config.js"]) {
    if (await exists(join(dir, name))) return "static";
  }
  if (await exists(join(dir, "public"))) return "static";
  return "node";
}

/** A safe starter config when no `--url` is supplied. */
function stubConfig(url: string | undefined, name: string | undefined): GraphewayConfig {
  let origin = "https://example.com";
  if (url) {
    try {
      origin = new URL(url).origin;
    } catch {
      // Keep the placeholder if the URL is malformed.
    }
  }
  let host = "example.com";
  try {
    host = new URL(origin).hostname.replace(/^www\./, "");
  } catch {
    // Keep the placeholder.
  }
  return {
    name: name ?? host,
    url: origin,
    tagline: "Native agent access for this site",
    summary:
      "This site publishes a live knowledge graph, an agent manifest and an open MCP endpoint so AI agents can read and act on it without scraping.",
    capabilities: ["graph", "search", "mcp"],
    sections: [],
    actions: [],
  };
}

function configSource(config: GraphewayConfig): string {
  return `import type { GraphewayConfig } from "grapheway";

/**
 * grapheway.config.ts — the single source of truth for this site's
 * agent surface. Every node, edge, section and action is yours to edit.
 */
export const graphewayConfig: GraphewayConfig = ${JSON.stringify(config, null, 2)};

export default graphewayConfig;
`;
}

const MIDDLEWARE_SOURCE = `import { NextResponse, type NextRequest } from "next/server";

/**
 * Rewrite the grapheway agent surface (/mcp, /graph, /agent, discovery)
 * to a single route handler. Generated by \`grapheway init\`.
 */
export function middleware(request: NextRequest) {
  const pathname = request.nextUrl.pathname;
  const url = request.nextUrl.clone();
  url.pathname = "/api/grapheway";
  const headers = new Headers(request.headers);
  headers.set("x-grapheway-path", pathname);
  return NextResponse.rewrite(url, { request: { headers } });
}

export const config = {
  matcher: ["/.well-known/agent", "/graph", "/graph/:path*", "/agent", "/agent/:path*", "/mcp"],
};
`;

const ROUTE_SOURCE = `import { createGrapheway, toFetchHandler } from "grapheway/web";
import { graphewayConfig } from "../../../grapheway.config";

const agent = createGrapheway(graphewayConfig);
const handler = toFetchHandler(agent.handler);

export const dynamic = "force-dynamic";
export const runtime = "nodejs";

export const GET = handler;
export const POST = handler;
export const OPTIONS = handler;
`;

async function writeSafe(
  path: string,
  content: string,
  force: boolean,
  files: string[],
  skipped: string[],
  root: string,
): Promise<void> {
  if (!force && (await exists(path))) {
    skipped.push(relative(root, path));
    return;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content, "utf-8");
  files.push(relative(root, path));
}

const MOUNT_SNIPPETS: Record<Exclude<Framework, "static">, string[]> = {
  next: [],
  express: [
    "// server.ts",
    'import { createGrapheway, toExpressHandler } from "grapheway/web";',
    'import { graphewayConfig } from "./grapheway.config";',
    "",
    "const agent = createGrapheway(graphewayConfig);",
    "app.use(toExpressHandler(agent.handler));",
  ],
  hono: [
    "// server.ts",
    'import { createGrapheway, toHonoHandler } from "grapheway/web";',
    'import { graphewayConfig } from "./grapheway.config";',
    "",
    "const agent = createGrapheway(graphewayConfig);",
    'app.all("*", toHonoHandler(agent.handler));',
  ],
  node: [
    "// server.ts",
    'import { createServer } from "node:http";',
    'import { createGrapheway, toNodeHandler } from "grapheway/web";',
    'import { graphewayConfig } from "./grapheway.config";',
    "",
    "const agent = createGrapheway(graphewayConfig);",
    "createServer(toNodeHandler(agent.handler)).listen(3000);",
  ],
};

/**
 * Scaffold grapheway into a project. Safe by default: existing files are
 * never overwritten unless `force` is set.
 */
export async function scaffoldProject(options: InitOptions = {}): Promise<InitResult> {
  const root = resolve(options.dir ?? process.cwd());
  const framework = options.framework ?? (await detectFramework(root));
  const files: string[] = [];
  const skipped: string[] = [];

  let config = stubConfig(options.url, options.name);
  let probed = false;

  if (options.url) {
    try {
      const result = await probeSite(options.url, {
        maxDepth: 2,
        maxPages: options.maxPages ?? 20,
      });
      config = result.config;
      config.url = new URL(options.url).origin;
      if (options.name) config.name = options.name;
      probed = true;
    } catch {
      // Offline / blocked / invalid URL: keep the stub and tell the user.
    }
  }

  const useSrc = (await exists(join(root, "src", "app"))) && !(await exists(join(root, "app")));
  const configDir = useSrc ? join(root, "src") : root;
  const configPath = join(configDir, "grapheway.config.ts");

  await writeSafe(configPath, configSource(config), options.force ?? false, files, skipped, root);

  let middlewareNeedsMerge = false;

  if (framework === "next") {
    const appDir = useSrc ? join(root, "src", "app") : join(root, "app");
    const middlewarePath = join(configDir, "middleware.ts");

    // Never clobber an existing middleware — it may contain auth, redirects
    // or localization. Write a mergeable file instead and tell the user.
    if (await exists(middlewarePath)) {
      const mergePath = join(configDir, "middleware.grapheway.ts");
      await writeSafe(mergePath, MIDDLEWARE_SOURCE, true, files, skipped, root);
      skipped.push(relative(root, middlewarePath));
      middlewareNeedsMerge = true;
    } else {
      await writeSafe(middlewarePath, MIDDLEWARE_SOURCE, false, files, skipped, root);
    }

    await writeSafe(
      join(appDir, "api", "grapheway", "route.ts"),
      ROUTE_SOURCE,
      options.force ?? false,
      files,
      skipped,
      root,
    );
  }

  if (framework === "static") {
    const publicDir = join(root, "public");
    await mkdir(publicDir, { recursive: true });
    for (const [name, content] of Object.entries(generateAll(config))) {
      await writeSafe(join(publicDir, name), content, options.force ?? false, files, skipped, root);
    }
  }

  const nextSteps: string[] = [];
  if (framework === "next") {
    if (middlewareNeedsMerge) {
      nextSteps.push(
        "Existing middleware.ts found — merge the rewrite from middleware.grapheway.ts into it",
      );
    }
    nextSteps.push(
      "Run your dev server (e.g. `npm run dev`)",
      "Open http://localhost:3000/graph to see the live graph",
      "Point any MCP client at http://localhost:3000/mcp",
    );
  } else if (framework === "static") {
    nextSteps.push(
      "Static files written to ./public (llms.txt, agents.txt, agents.json, robots.txt, sitemap.xml)",
      "A static host cannot run /mcp or /graph/v1 — run `npx grapheway gateway --config grapheway.config.ts` for the full surface",
    );
  } else {
    nextSteps.push("Mount the handler with the snippet below:", ...MOUNT_SNIPPETS[framework]);
  }
  return { framework, files, skipped, probed, nextSteps };
}
