#!/usr/bin/env node
/**
 * Local developer convenience.
 *
 * `npx grapheway` inside the monorepo resolves the workspace package, but the
 * root `node_modules/.bin` does not get a linked binary from Bun. That makes
 * `npx grapheway` fail with "command not found" even though the published
 * package works.
 *
 * This script creates local `.bin/grapheway` wrappers that point at the
 * TypeScript CLI source through Bun. It runs from `postinstall` and can be run
 * manually with `bun run link:cli`.
 *
 * It is local only. It is not part of the published package.
 */

import { chmod, mkdir, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cli = join(root, "packages", "grapheway", "src", "cli", "cli.ts");

const targets = [
  join(root, "node_modules", ".bin"),
  join(root, "website", "node_modules", ".bin"),
];

for (const binDir of targets) {
  const wrapper = join(binDir, "grapheway");
  const rel = relative(binDir, cli);
  await mkdir(binDir, { recursive: true });
  await writeFile(
    wrapper,
    `#!/bin/sh\n# Local grapheway CLI wrapper. Generated by scripts/link-local-cli.mjs.\nset -e\nDIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)\nexec bun run "$DIR/${rel}" "$@"\n`,
    "utf-8",
  );
  await chmod(wrapper, 0o755);
  console.log(`linked ${wrapper}`);
}
